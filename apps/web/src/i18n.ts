const catalogs: Record<Locale, Record<MessageKey, string>> = { zh, en };
export type MessageKey = keyof typeof zh;

let currentLocale: Locale = detectLocale();

function readStoredLocale(): Locale | undefined {
  try {
    if (typeof localStorage === "undefined" || typeof localStorage.getItem !== "function") return undefined;
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved === "zh" || saved === "en" ? saved : undefined;
  } catch {
    return undefined;
  }
}

export function detectLocale(): Locale {
  const saved = readStoredLocale();
  if (saved) return saved;
  if (
    typeof document !== "undefined" &&
    typeof navigator !== "undefined" &&
    navigator.language?.toLowerCase().startsWith("en")
  )
    return "en";
  return "zh";
}

export function getLocale(): Locale {
  return currentLocale;
}

export function localeTag(locale: Locale = currentLocale): string {
  return locale === "en" ? "en-US" : "zh-CN";
}

export function acceptLanguageHeader(locale: Locale = currentLocale): string {
  return locale === "en" ? "en" : "zh-CN";
}

export function applyLocale(locale: Locale): void {
  currentLocale = locale;
  try {
    if (typeof localStorage !== "undefined" && typeof localStorage.setItem === "function") {
      localStorage.setItem(STORAGE_KEY, locale);
    }
  } catch {
    // Ignore storage failures in non-browser test hosts.
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = localeTag(locale);
    document.title = translate(locale, "appTitle");
  }
  listeners.forEach((listener) => listener());
}

export function subscribeLocale(listener: () => void): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function interpolate(template: string, vars?: MessageVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => (vars[key] === undefined ? `{${key}}` : String(vars[key])));
}

export function translate(locale: Locale, key: MessageKey, vars?: MessageVars): string {
  return interpolate(catalogs[locale][key] ?? catalogs.zh[key] ?? key, vars);
}

export function t(key: MessageKey, vars?: MessageVars): string {
  return translate(currentLocale, key, vars);
}

export function useLocale() {
  const locale = useSyncExternalStore(subscribeLocale, getLocale, getLocale);
  return useMemo(
    () => ({
      locale,
      setLocale: applyLocale,
      t: (key: MessageKey, vars?: MessageVars) => translate(locale, key, vars)
    }),
    [locale]
  );
}

export function localizedProfile(id: string, fallbackName?: string, fallbackDescription?: string) {
  if (id === "graduate-admissions") return { name: t("profileAdmissions"), description: t("profileAdmissionsDesc") };
  if (id === "local-operator") return { name: t("profileLocal"), description: t("profileLocalDesc") };
  return { name: fallbackName ?? id, description: fallbackDescription ?? "" };
}

export function statusMessage(value?: string): string {
  const normalized = value?.toLowerCase();
  if (normalized === "completed" || normalized === "done" || normalized === "succeeded") return t("statusDone");
  if (normalized === "failed") return t("statusFailed");
  if (normalized === "running") return t("statusRunning");
  if (normalized === "submitted") return t("statusSubmitted");
  if (normalized === "researching") return t("statusResearching");
  if (normalized === "shortlisted") return t("statusShortlisted");
  if (normalized === "applying") return t("statusApplying");
  if (normalized === "interview") return t("statusInterview");
  if (normalized === "offer") return t("statusOffer");
  if (normalized === "rejected") return t("statusRejected");
  if (normalized === "withdrawn") return t("statusWithdrawn");
  if (normalized === "missing") return t("statusMissing");
  if (normalized === "in_progress") return t("statusInProgress");
  if (normalized === "ready") return t("statusReady");
  if (normalized === "waived") return t("statusWaived");
  return value || t("statusPending");
}

export function regionMessage(region: string): string {
  const key = region.trim().toLowerCase();
  if (["美国", "usa", "us", "united states"].includes(key) || region === "美国") return t("regionUS");
  if (["加拿大", "canada"].includes(key) || region === "加拿大") return t("regionCA");
  if (["香港", "hong kong", "hk"].includes(key) || region === "香港") return t("regionHK");
  if (["新加坡", "singapore", "sg"].includes(key) || region === "新加坡") return t("regionSG");
  return region;
}

